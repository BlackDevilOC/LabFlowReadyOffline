def check_db_health() -> Dict[str, Any]:
    """
    Live health probe for local PostgreSQL database.
    Measures connection status, query latency, active connections, and PostgreSQL version.
    """
    cfg = get_db_config()
    start_time = time.time()

    try:
        conn = get_connection()
        cursor = conn.cursor(cursor_factory=RealDictCursor)

        # Query version & active connections
        cursor.execute("SELECT version();")
        version_info = cursor.fetchone()["version"]

        cursor.execute("SELECT count(*) as active_conns FROM pg_stat_activity WHERE datname = %s;", (cfg["dbname"],))
        active_conns = cursor.fetchone()["active_conns"]

        # Count total tables
        cursor.execute("""
            SELECT count(*) as table_count 
            FROM information_schema.tables 
            WHERE table_schema = 'public';
        """)
        table_count = cursor.fetchone()["table_count"]

        latency_ms = round((time.time() - start_time) * 1000, 2)

        cursor.close()
        conn.close()

        return {
            "status": "healthy",
            "database_name": cfg["dbname"],
            "host": cfg["host"],
            "port": cfg["port"],
            "latency_ms": latency_ms,
            "version": version_info.split(",")[0],
            "active_connections": active_conns,
            "total_tables": table_count,
            "message": f"Local PostgreSQL is online and responsive ({latency_ms} ms)."
        }
    except Exception as e:
        latency_ms = round((time.time() - start_time) * 1000, 2)
        return {
            "status": "unhealthy",
            "database_name": cfg["dbname"],
            "host": cfg["host"],
            "port": cfg["port"],
            "latency_ms": latency_ms,
            "error": str(e),
            "message": f"Failed to connect to local PostgreSQL: {e}"
        }


def get_table_status() -> List[Dict[str, Any]]:
    """
    Inspects all tables in the local PostgreSQL database, returning names, row counts, and status.
    """
    tables_info = []
    expected_tables = [
        "patients", "test_results_all", "tests", "test_groups",
        "shift", "users", "remarks", "invoice_settings",
        "print_settings", "app_settings", "analytics_snapshots"
    ]

    try:
        conn = get_connection()
        cursor = conn.cursor()

        for tbl in expected_tables:
            try:
                cursor.execute(f"SELECT COUNT(*) FROM public.{tbl};")
                count = cursor.fetchone()[0]
                tables_info.append({
                    "table_name": tbl,
                    "exists": True,
                    "row_count": count,
                    "status": "Ready"
                })
            except Exception:
                conn.rollback()
                tables_info.append({
                    "table_name": tbl,
                    "exists": False,
                    "row_count": 0,
                    "status": "Missing"
                })

        cursor.close()
        conn.close()
    except Exception as e:
        logger.error(f"Failed to inspect tables: {e}")

    return tables_info


