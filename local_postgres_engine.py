def init_local_schema() -> Tuple[bool, str]:
    """Ensures database exists and initializes all 11 core tables and indexes."""
    db_ok, db_msg = ensure_database_exists()
    if not db_ok:
        return False, f"Cannot initialize schema: {db_msg}"

    try:
        conn = get_connection()
        cursor = conn.cursor()

        for statement in CORE_SCHEMA_DDL:
            cursor.execute(statement)

        conn.commit()
        cursor.close()
        conn.close()

        logger.info("Successfully verified and initialized all 11 local PostgreSQL tables.")
        seed_initial_defaults()
        return True, "All 11 local PostgreSQL tables and indexes are initialized."
    except Exception as e:
        err_msg = f"Schema initialization failed: {e}"
        logger.error(err_msg)
        return False, err_msg


