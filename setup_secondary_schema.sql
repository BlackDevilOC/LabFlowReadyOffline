-- 1. Patients Table
DROP TABLE IF EXISTS public.patients CASCADE;
CREATE TABLE IF NOT EXISTS public.patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMPTZ DEFAULT now(),
    mr_no BIGINT PRIMARY KEY,
    salutation TEXT,
    patient_name TEXT,
    relation TEXT,
    relation_name TEXT,
    mobile TEXT,
    gender TEXT,
    age INTEGER,
    cnic TEXT,
    patient_token INTEGER DEFAULT 0,
    shift TEXT,
    "user" TEXT,
    user_id BIGINT,
    pwd TEXT
);

-- 2. Test Results Table
DROP TABLE IF EXISTS public.test_results_all CASCADE;
CREATE TABLE IF NOT EXISTS public.test_results_all (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mr_no BIGINT,
    patient_name TEXT,
    category TEXT,
    test_name TEXT,
    test_values JSONB DEFAULT '{}'::jsonb,
    status TEXT DEFAULT 'Pending',
    created_at TIMESTAMPTZ DEFAULT now(),
    delete_status INTEGER DEFAULT 0,
    person_deleting TEXT,
    remarks TEXT
);

-- 3. Tests Catalog
DROP TABLE IF EXISTS public.tests CASCADE;
CREATE TABLE IF NOT EXISTS public.tests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now(),
    name TEXT,
    unit TEXT,
    normal_min TEXT,
    normal_max TEXT,
    status BOOLEAN DEFAULT true,
    category TEXT
);

-- 4. Test Groups
DROP TABLE IF EXISTS public.test_groups CASCADE;
CREATE TABLE IF NOT EXISTS public.test_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name TEXT,
    component_ids JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT now(),
    status BOOLEAN DEFAULT true,
    category TEXT
);

-- 5. Shifts
DROP TABLE IF EXISTS public.shift CASCADE;
CREATE TABLE IF NOT EXISTS public.shift (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now(),
    shift TEXT UNIQUE NOT NULL
);

-- 6. Users
DROP TABLE IF EXISTS public.users CASCADE;
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT now(),
    email TEXT UNIQUE NOT NULL,
    pwd TEXT NOT NULL,
    name TEXT,
    is_active BOOLEAN DEFAULT true,
    permissions JSONB DEFAULT '{}'::jsonb,
    default_shift_id BIGINT
);

-- 7. Common Remarks
DROP TABLE IF EXISTS public.remarks CASCADE;
CREATE TABLE IF NOT EXISTS public.remarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remark_text TEXT,
    test_name TEXT,
    category TEXT,
    usage_count INTEGER DEFAULT 0,
    sort_order INTEGER DEFAULT 0,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- 8. Invoice Settings
DROP TABLE IF EXISTS public.invoice_settings CASCADE;
CREATE TABLE IF NOT EXISTS public.invoice_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_name TEXT,
    developed_by TEXT,
    developed_by_url TEXT,
    online_report_url TEXT,
    printer_width TEXT,
    logo_path TEXT,
    qr_code_path TEXT,
    is_active BOOLEAN DEFAULT true,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- 9. Print Settings (Full 60 Columns)
DROP TABLE IF EXISTS public.print_settings CASCADE;
CREATE TABLE IF NOT EXISTS public.print_settings (
    id BIGINT PRIMARY KEY,
    bg_light TEXT,
    border_color TEXT,
    category_border_width NUMERIC,
    category_font_size INTEGER,
    category_padding_bottom NUMERIC,
    category_padding_top NUMERIC,
    col_range_align TEXT,
    col_range_width NUMERIC,
    col_result_align TEXT,
    col_result_width NUMERIC,
    col_test_name_align TEXT,
    col_test_name_width NUMERIC,
    col_unit_align TEXT,
    col_unit_width NUMERIC,
    combine_categories_on_same_page INTEGER,
    created_at TIMESTAMPTZ,
    created_by TEXT,
    display_pathologist_signature INTEGER,
    display_verified_by INTEGER,
    footer_font_size INTEGER,
    footer_line1 TEXT,
    footer_line2 TEXT,
    footer_line3 TEXT,
    footer_margin_top NUMERIC,
    footer_padding_top NUMERIC,
    group_font_size INTEGER,
    group_padding_bottom NUMERIC,
    group_padding_left NUMERIC,
    group_padding_top NUMERIC,
    header_bottom_margin NUMERIC,
    header_height NUMERIC,
    hide_single_param_title INTEGER,
    is_active BOOLEAN DEFAULT true,
    page_bottom_margin NUMERIC,
    page_left_margin NUMERIC,
    page_right_margin NUMERIC,
    page_top_margin NUMERIC,
    patient_info_border_radius NUMERIC,
    patient_info_bottom_margin NUMERIC,
    patient_info_font_size INTEGER,
    patient_info_label_font_size INTEGER,
    patient_info_label_width NUMERIC,
    patient_info_min_height NUMERIC,
    patient_info_padding_horizontal NUMERIC,
    patient_info_padding_vertical NUMERIC,
    patient_info_row_gap NUMERIC,
    primary_color TEXT,
    result_font_size INTEGER,
    secondary_color TEXT,
    signature_block_min_width NUMERIC,
    table_cell_padding_horizontal NUMERIC,
    table_cell_padding_vertical NUMERIC,
    table_header_padding_horizontal NUMERIC,
    table_header_padding_vertical NUMERIC,
    test_name_font_size INTEGER,
    text_main TEXT,
    text_muted TEXT,
    updated_at TIMESTAMPTZ DEFAULT now(),
    updated_by TEXT
);

-- 10. App Settings
DROP TABLE IF EXISTS public.app_settings CASCADE;
CREATE TABLE IF NOT EXISTS public.app_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_type TEXT UNIQUE,
    payload JSONB,
    updated_by TEXT,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- 11. Analytics Snapshots
DROP TABLE IF EXISTS public.analytics_snapshots CASCADE;
CREATE TABLE IF NOT EXISTS public.analytics_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_date DATE,
    metrics JSONB,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Indexes for maximum lookup speed
CREATE INDEX IF NOT EXISTS idx_patients_mr_no ON public.patients(mr_no);
CREATE INDEX IF NOT EXISTS idx_test_results_mr_no ON public.test_results_all(mr_no);
CREATE INDEX IF NOT EXISTS idx_test_results_status ON public.test_results_all(status);

-- Grant full table & sequence permissions to API roles
GRANT ALL ON ALL TABLES IN SCHEMA public TO postgres, anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO postgres, anon, authenticated, service_role;
